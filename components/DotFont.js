var ROWS = 7
var GAP = 1 // empty columns between glyphs

function glyph(ch) {
  var g = GLYPHS[ch]
  if (!g) g = GLYPHS[String(ch).toUpperCase()]
  if (!g) g = GLYPHS["?"]
  return g
}

function glyphWidth(ch) {
  return glyph(ch)[0].length
}

// Total width in dot columns for a string (including inter-glyph gaps).
function textColumns(text) {
  var s = String(text || "")
  var w = 0
  for (var i = 0; i < s.length; i++) {
    if (i > 0) w += GAP
    w += glyphWidth(s.charAt(i))
  }
  return w
}

// Returns an array of {col, row} for every lit dot, plus the total columns.
function layout(text) {
  var s = String(text || "")
  var dots = []
  var x = 0
  for (var i = 0; i < s.length; i++) {
    if (i > 0) x += GAP
    var g = glyph(s.charAt(i))
    for (var r = 0; r < ROWS; r++) {
      var row = g[r] || ""
      for (var c = 0; c < row.length; c++) {
        if (row.charAt(c) === "#") dots.push({ col: x + c, row: r })
      }
    }
    x += g[0].length
  }
  return { dots: dots, columns: x, rows: ROWS }
}
